import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const code = await readFile(new URL('src/client-factory.js', root), 'utf8');
const { name } = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const dictionaries = {};
for (const locale of ['en', 'zh']) dictionaries[locale] = JSON.parse(await readFile(new URL(`locale/${locale}.json`, root), 'utf8'));
const factory = code.replace('export function clientFactory', 'function clientFactory');
await writeFile(new URL('client.js', root), `// Generated by npm run build. Edit src/client-factory.js and locale/*.json.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(name)},\n  factory(require) {\n${factory}\n    return clientFactory(require, ${JSON.stringify(dictionaries)});\n  },\n});\n`);
console.log('Built client.js');
