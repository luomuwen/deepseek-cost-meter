import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const code = await readFile(new URL('src/client-factory.js', root), 'utf8');
const { name, version } = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const dictionaries = {};
for (const locale of ['en', 'zh']) dictionaries[locale] = JSON.parse(await readFile(new URL(`locale/${locale}.json`, root), 'utf8'));
const helpers = await Promise.all(['src/client-balance.js', 'src/client-balance-view.js'].map(async file =>
  (await readFile(new URL(file, root), 'utf8')).replaceAll('export function ', 'function ')));
const factory = helpers.join('\n') + '\n' + code.replace(/^import .*;\n/gm, '').replace('export function clientFactory', 'function clientFactory');
await writeFile(new URL('client.js', root), `// Generated by npm run build. Edit src/client-*.js and locale/*.json.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(name)},\n  factory(require) {\n${factory}\n    return clientFactory(require, ${JSON.stringify(dictionaries)}, ${JSON.stringify(name + '/' + version)});\n  },\n});\n`);
console.log('Built client.js');
